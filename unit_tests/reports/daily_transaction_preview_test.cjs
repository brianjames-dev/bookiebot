assert.equal(layers()[3].findAllByProps({className:'bb-daily-bead'})[4],beads[4],'The same logo surface travels in both directions')
assert.equal(slot.props['data-ready'],true)
act(()=>{props={...props,month:12};renderer.update(React.createElement(DailyTransactionDays,props))})
assert.equal(rows().length,0,'Month changes discard retained day panels')
act(()=>renderer.unmount())
console.log('Date column: 1/2/3/7 entries, six icons plus exact overflow, Today, singular/plural counts, stable category order and persistent rows/images passed')
