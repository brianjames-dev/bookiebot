const assert=require('node:assert/strict'),path=require('node:path'),{createRequire}=require('node:module')
const req=createRequire(path.resolve('web/expense-report/package.json')),React=req('react'),{act,create}=req('react-test-renderer')
global.IS_REACT_ACT_ENVIRONMENT=true
const {DailyTransactionDays}=require('./load_frontend_module.cjs')('daily-transactions.tsx')
const entries=Array.from({length:7},(_,i)=>({date:'11/5/2026',category:i%2?'Shopping':'Food',amount:i+1,person:'Fixture',location:i%2?'Target':'Unknown café',item:'Purchase '+i,status:'recorded'}))
let props={groups:[1,2,3,7].map((n,i)=>({day:String(8-i),entries:entries.slice(0,n),today:false})),categoryColors:{Food:'red',Shopping:'blue'},year:2026,month:11},renderer
act(()=>{renderer=create(React.createElement(DailyTransactionDays,props))})
const previews=()=>renderer.root.findAllByProps({className:'bb-daily-preview'}),headers=()=>renderer.root.findAllByProps({className:'bb-daily-day-header'}),rows=()=>renderer.root.findAllByProps({className:'bb-daily-transaction'})
assert.deepEqual(previews().map(preview=>preview.findAllByProps({className:'bb-daily-preview-item'}).length),[1,2,3,3])
assert.deepEqual(previews().map(preview=>preview.findAllByProps({className:'bb-daily-preview-more'}).map(n=>n.children.join(''))),[[],[],['+1'],['+5']])
assert.ok(previews()[3].props['aria-label'].startsWith('7 transactions:'))
assert.equal(rows().length,0,'Closed days do not build transaction row components')
assert.equal(renderer.root.findAllByProps({className:'bb-daily-day-count'}).length,0)
act(()=>headers()[3].props.onClick())
assert.equal(rows().length,7)
assert.deepEqual(rows().map(row=>row.props['data-category']),['Food','Food','Food','Food','Shopping','Shopping','Shopping'])
const original=rows(),firstImage=original[4].findByType('img')
act(()=>firstImage.props.onLoad())
const slot=original[4].findByProps({className:'bb-transaction-icon'})
assert.equal(slot.props['data-ready'],true)
act(()=>headers()[3].props.onClick())
assert.equal(headers()[3].props['aria-expanded'],false)
assert.equal(rows()[4],original[4],'Closing retains the row and decoded image')
act(()=>headers()[3].props.onClick())
assert.equal(rows()[4],original[4],'Reopening does not remount transactions')
assert.equal(slot.props['data-ready'],true)
act(()=>{props={...props,month:12};renderer.update(React.createElement(DailyTransactionDays,props))})
assert.equal(rows().length,0,'Month changes discard retained day panels')
act(()=>renderer.unmount())
console.log('Day previews: 1/2/3/7 entries, two icons plus exact overflow, accessible counts, stable category order and retained rows/images passed')
