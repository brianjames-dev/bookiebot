// A reused slot must not show a previous source's loaded/failed state.
let renderer
act(()=>{renderer=create(React.createElement(TransactionIcon,{entry:input({item:'Target'})}))})
const image=()=>renderer.root.findByType('img'),slot=()=>renderer.root.findByProps({className:'bb-transaction-icon'})
