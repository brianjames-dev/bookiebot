global.IS_REACT_ACT_ENVIRONMENT=true
const load=require('./load_frontend_module.cjs'),{transactionMerchant,transactionCategory,transactionText}=load('transaction-identity.ts'),{TransactionIcon}=load('daily-transactions.tsx')
